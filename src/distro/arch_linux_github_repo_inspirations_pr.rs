// 7. ARCH-TESTING SIGNOFF TRACKER ENGINE (`archlinux/arch-testing`)
// =========================================================================

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SignoffVote {
    SignedOff,
    Revoked,
    FailedTesting,
}

#[derive(Debug, Clone)]
pub struct TestingPackageSignoff {
    pub package_name: String,
    pub version: String,
    pub repo: String,
    pub required_signoffs: usize,
    pub signoffs: BTreeMap<String, SignoffVote>, // Maintainer -> Vote
}

#[derive(Debug, Clone)]
pub struct ArchTestingSignoffTrackerEngine {
    packages: BTreeMap<String, TestingPackageSignoff>,
}

impl ArchTestingSignoffTrackerEngine {
    pub fn new() -> Self {
        Self {
            packages: BTreeMap::new(),
        }
    }

    pub fn register_testing_package(&mut self, name: &str, version: &str, repo: &str, required_signoffs: usize) {
        self.packages.insert(
            name.to_string(),
            TestingPackageSignoff {
                package_name: name.to_string(),
                version: version.to_string(),
                repo: repo.to_string(),
                required_signoffs,
                signoffs: BTreeMap::new(),
            },
        );
    }

    pub fn sign_off(&mut self, package_name: &str, maintainer: &str, vote: SignoffVote) -> bool {
        if let Some(pkg) = self.packages.get_mut(package_name) {
            pkg.signoffs.insert(maintainer.to_string(), vote);
            return true;
        }
        false
    }

    pub fn is_ready_for_release(&self, package_name: &str) -> bool {
        if let Some(pkg) = self.packages.get(package_name) {
            let positive_votes = pkg
                .signoffs
                .values()
                .filter(|v| *v == &SignoffVote::SignedOff)
                .count();
            let has_failures = pkg
                .signoffs
                .values()
                .any(|v| v == &SignoffVote::FailedTesting);
            return !has_failures && positive_votes >= pkg.required_signoffs;
        }
        false
    }

    pub fn submit_pr(&self, pr_id: u32) -> ArchGithubRepoInspirationsPrProposal {
        ArchGithubRepoInspirationsPrProposal {
            pr_id,
            title: "Arch-Testing: Staging Signoff Tracker & Package Release Gate Engine".to_string(),
            source_repo: "archlinux/arch-testing".to_string(),
            target_component: "src/distro/arch_testing_gate.rs".to_string(),
            branch: "feature/arch-testing-signoff".to_string(),
            status: ArchPrStatus::Merged,
            capability_score: 90,
            description: "Collaborative staging signoff ledger ensuring test coverage before core repository graduation".to_string(),
        }
    }
}

impl Default for ArchTestingSignoffTrackerEngine {
    fn default() -> Self {
        Self::new()
    }
}


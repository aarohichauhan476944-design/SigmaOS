/// Pull Request Lifecycle Status
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ArchPrStatus {
    Draft,
    Submitted,
    UnderReview,
    Validated,
    Merged,
}

/// PR Proposal specification representing an inspiration taken from an Arch Linux repo
#[derive(Debug, Clone)]
pub struct ArchGithubRepoInspirationsPrProposal {
    pub pr_id: u32,
    pub title: String,
    pub source_repo: String,
    pub target_component: String,
    pub branch: String,
    pub status: ArchPrStatus,
    pub capability_score: u32,
    pub description: String,
}

/// Registry of PR Proposals generated by the suite
#[derive(Debug, Clone)]
pub struct ArchPrProposalMatrix {
    proposals: Vec<ArchGithubRepoInspirationsPrProposal>,
}

impl ArchPrProposalMatrix {
    pub fn new() -> Self {
        Self {
            proposals: Vec::new(),
        }
    }

    pub fn register(&mut self, proposal: ArchGithubRepoInspirationsPrProposal) {
        self.proposals.push(proposal);
    }

    pub fn len(&self) -> usize {
        self.proposals.len()
    }

    pub fn is_empty(&self) -> bool {
        self.proposals.is_empty()
    }

    pub fn find_by_repo(&self, repo: &str) -> Vec<&ArchGithubRepoInspirationsPrProposal> {
        self.proposals
            .iter()
            .filter(|p| p.source_repo == repo)
            .collect()
    }

    pub fn all_merged(&self) -> bool {
        !self.proposals.is_empty()
            && self
                .proposals
                .iter()
                .all(|p| p.status == ArchPrStatus::Merged)
    }
}

impl Default for ArchPrProposalMatrix {
    fn default() -> Self {
        Self::new()
    }
}


// 4. REFLECTOR MIRRORLIST RANKER ENGINE (`archlinux/reflector`)
// =========================================================================

#[derive(Debug, Clone)]
pub struct MirrorEntry {
    pub url: String,
    pub country: String,
    pub latency_ms: u32,
    pub completion_percent: u8,
    pub score: f64,
}

#[derive(Debug, Clone)]
pub struct ArchReflectorMirrorlistRankerEngine {
    pub mirrors: Vec<MirrorEntry>,
    pub max_latency_threshold_ms: u32,
    pub required_completion: u8,
}

impl ArchReflectorMirrorlistRankerEngine {
    pub fn new(max_latency_threshold_ms: u32) -> Self {
        Self {
            mirrors: Vec::new(),
            max_latency_threshold_ms,
            required_completion: 100,
        }
    }

    pub fn add_mirror(&mut self, url: &str, country: &str, latency_ms: u32, completion_percent: u8) {
        let score = if latency_ms > 0 {
            (completion_percent as f64) * 10.0 / (latency_ms as f64)
        } else {
            0.0
        };
        self.mirrors.push(MirrorEntry {
            url: url.to_string(),
            country: country.to_string(),
            latency_ms,
            completion_percent,
            score,
        });
    }

    pub fn rank_and_filter(&self, top_n: usize) -> Vec<MirrorEntry> {
        let mut valid: Vec<MirrorEntry> = self
            .mirrors
            .iter()
            .filter(|m| m.latency_ms <= self.max_latency_threshold_ms && m.completion_percent >= self.required_completion)
            .cloned()
            .collect();
        valid.sort_by(|a, b| b.score.partial_cmp(&a.score).unwrap_or(core::cmp::Ordering::Equal));
        valid.truncate(top_n);
        valid
    }

    pub fn generate_pacman_mirrorlist(&self, top_n: usize) -> String {
        let ranked = self.rank_and_filter(top_n);
        let mut out = String::from("## SigmaOS Pacman Mirrorlist (Auto-generated by Reflector Engine)\n");
        for m in ranked {
            out.push_str(&format!("Server = {}/$repo/os/$arch\n", m.url));
        }
        out
    }

    pub fn submit_pr(&self, pr_id: u32) -> ArchGithubRepoInspirationsPrProposal {
        ArchGithubRepoInspirationsPrProposal {
            pr_id,
            title: "Reflector: Pacman Mirror Ranking & Latency Optimizer Engine".to_string(),
            source_repo: "archlinux/reflector".to_string(),
            target_component: "src/net/reflector_mirror_ranker.rs".to_string(),
            branch: "feature/reflector-mirror-optimizer".to_string(),
            status: ArchPrStatus::Merged,
            capability_score: 91,
            description: "High-speed mirror list evaluation with sync state verification and latency weighting".to_string(),
        }
    }
}

